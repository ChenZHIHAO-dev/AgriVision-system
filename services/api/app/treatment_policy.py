"""区分防治知识和需要产品标签审核的具体施用问题。

说明病害管理方向可以使用资料检索回答；每亩用量、兑水或混配属于
具体产品的使用条件，不能由分类分数或语言模型自行换算。
"""
import re

MEDICATION = re.compile(
    r"配方|剂量|用量|混配|兑水|农药|打药|用药|药剂|药物|用什么药|喷什么|多少.*(?:克|毫升|倍)"
)
PRECISE_APPLICATION = re.compile(
    r"配方|剂量|用量|混配|混用|兑水|稀释|配比|配药|安全间隔|"
    r"(?:怎么|怎样|如何).{0,6}(?:配|兑)|(?:能否|能不能|可以).{0,8}(?:一起|混)|"
    r"(?:多少|几|多大).{0,6}(?:克|毫升|升|斤|倍|浓度)|"
    r"(?:喷|打|施).{0,4}(?:几次|多少次)|(?:间隔|隔).{0,3}(?:几|多少).{0,2}天"
)
LABEL_READING = re.compile(r"(?:农药|产品)?标签|(?:用药|施药|喷药)前.{0,8}核对")
# 阻止未核验的定量施用建议直接进入生成回复；数值核对由产品资料模块负责。
DOSAGE = re.compile(r"\d+(?:\.\d+)?\s*(?:毫升|ml\b|克|g\b|倍液)", re.I)


def requires_label_review(text):
    """只把标签阅读、剂量与混配交给明确的审核流程，不截断普通防治追问。"""
    return bool(PRECISE_APPLICATION.search(text) or LABEL_READING.search(text))
